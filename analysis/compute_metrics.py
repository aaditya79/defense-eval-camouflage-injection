"""
compute_metrics.py — Aggregate detection metrics from all trial JSONL files.

Reads results/trials_{model}.jsonl for each model, computes per-detector
IDR (with 95% Wilson CI), CDG (with Newcombe CI), and Cohen's h, then
writes a LaTeX-ready summary table and paper_numbers.txt.

Usage:
  cd grounded-guard
  python analysis/compute_metrics.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.utils.trial_logger import load_all_trials
from analysis.significance_tests import (
    compute_wilson_ci,
    compute_bootstrap_ci,
    compute_cohens_h,
    compute_newcombe_ci,
    mcnemar_test,
    task_level_detection,
)

RESULTS_DIR = Path("results")
DETECTOR_ORDER = ["static", "augmented", "llama_guard", "grounded_guard"]
DETECTOR_DISPLAY = {
    "static":         "Static (few-shot)",
    "augmented":      "Augmented (few-shot+)",
    "llama_guard":    "Llama Guard 3",
    "grounded_guard": "GroundedGuard (ours)",
}


# ---------------------------------------------------------------------------
# Per-detector metrics computation
# ---------------------------------------------------------------------------

def compute_detector_metrics(
    trials: list[dict],
    detector_type: str,
) -> dict:
    """Compute IDR_static, IDR_cam, CDG with CIs for one detector."""
    static_trials = [t for t in trials if t.get("payload_type") == "static"]
    cam_trials    = [t for t in trials if t.get("payload_type") == "camouflage"]

    def _flagged(trial_list: list[dict]) -> int:
        return sum(
            1 for t in trial_list
            if t.get("verdicts", {}).get(detector_type, {}).get("verdict") == "INJECTED"
        )

    n_s_flag = _flagged(static_trials)
    n_c_flag = _flagged(cam_trials)
    n_s      = len(static_trials)
    n_c      = len(cam_trials)

    idr_s = n_s_flag / n_s if n_s else 0.0
    idr_c = n_c_flag / n_c if n_c else 0.0
    cdg   = idr_s - idr_c

    wilson_s   = compute_wilson_ci(n_s_flag, n_s)
    wilson_c   = compute_wilson_ci(n_c_flag, n_c)
    newcombe   = compute_newcombe_ci(idr_s, n_s, idr_c, n_c)
    cohens_h_s = compute_cohens_h(idr_s, 0.0)   # vs baseline of 0 detection
    cohens_h_c = compute_cohens_h(idr_c, 0.0)
    cohens_h_gap = compute_cohens_h(idr_s, idr_c)

    return {
        "detector":      detector_type,
        "idr_static":    round(idr_s, 4),
        "idr_cam":       round(idr_c, 4),
        "cdg":           round(cdg, 4),
        "n_static":      n_s,
        "n_cam":         n_c,
        "wilson_ci_static": (round(wilson_s[0], 4), round(wilson_s[1], 4)),
        "wilson_ci_cam":    (round(wilson_c[0], 4), round(wilson_c[1], 4)),
        "newcombe_ci_cdg":  (round(newcombe[0], 4), round(newcombe[1], 4)),
        "cohens_h_gap":     round(cohens_h_gap, 4),
    }


def compute_mcnemar_vs_static(
    trials: list[dict],
    detector_type: str,
    payload_type: str = "camouflage",
) -> dict:
    """McNemar's test comparing detector_type vs static baseline on payload_type."""
    det_a = task_level_detection(trials, "static",       payload_type)
    det_b = task_level_detection(trials, detector_type,  payload_type)
    common = sorted(set(det_a) & set(det_b))
    if not common:
        return {"chi2": float("nan"), "p": float("nan"), "b": 0, "c": 0}

    b = c = 0
    for tid in common:
        ra, rb = det_a[tid], det_b[tid]
        if ra and not rb:     b += 1
        elif not ra and rb:   c += 1

    chi2, p = mcnemar_test(b, c)
    return {
        "chi2":  round(chi2, 3) if not np.isnan(chi2) else None,
        "p":     round(p, 6)    if not np.isnan(p)    else None,
        "b":     b,
        "c":     c,
        "n_pairs": len(common),
    }


# ---------------------------------------------------------------------------
# LaTeX table generator
# ---------------------------------------------------------------------------

def _fmt_pct(v: float) -> str:
    return f"{v*100:.1f}\\%"


def _fmt_ci(lo: float, hi: float) -> str:
    return f"[{lo*100:.1f}, {hi*100:.1f}]"


def generate_latex_table(all_metrics: dict[str, list[dict]], output_path: Path) -> None:
    """
    Generate a LaTeX table comparing all four detectors across models.
    Format: one sub-table per model; rows = detectors; cols = IDR_s, IDR_c, CDG, h.
    """
    lines = [
        "% Auto-generated by analysis/compute_metrics.py",
        "\\begin{table*}[t]",
        "\\centering",
        "\\footnotesize",
        "\\setlength{\\tabcolsep}{4pt}",
        "\\begin{tabular}{l" + "c" * 4 + "}",
        "\\toprule",
        "\\textbf{Detector} & \\textbf{IDR$_{\\text{static}}$} & \\textbf{IDR$_{\\text{cam}}$} & \\textbf{CDG} & \\textbf{Cohen's $h$} \\\\",
        "\\midrule",
    ]

    for model_label, metrics_list in sorted(all_metrics.items()):
        lines.append(f"\\multicolumn{{5}}{{l}}{{\\textit{{Model: {model_label}}}}} \\\\")
        for m in metrics_list:
            row = (
                f"{DETECTOR_DISPLAY.get(m['detector'], m['detector'])} & "
                f"{_fmt_pct(m['idr_static'])} & "
                f"{_fmt_pct(m['idr_cam'])} & "
                f"{_fmt_pct(m['cdg'])} & "
                f"{m['cohens_h_gap']:.3f} \\\\"
            )
            if m["detector"] == "grounded_guard":
                row = "\\textbf{" + row.replace(" \\\\", "} \\\\")
            lines.append(row)
        lines.append("\\midrule")

    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\caption{Detection rates (IDR) and Camouflage Detection Gap (CDG) across four detectors. "
        "CDG = IDR$_{\\text{static}}$ $-$ IDR$_{\\text{camouflage}}$. "
        "Cohen's $h$ measures gap effect size. \\textbf{Bold} = proposed GroundedGuard.}",
        "\\label{tab:detection_comparison}",
        "\\end{table*}",
    ]

    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"LaTeX table written to: {output_path}")


# ---------------------------------------------------------------------------
# paper_numbers.txt writer
# ---------------------------------------------------------------------------

def write_paper_numbers(
    all_metrics: dict[str, list[dict]],
    all_mcnemar: dict[str, dict[str, dict]],
    output_path: Path,
) -> None:
    """Write all key numbers formatted for inline paper citation."""
    lines = [
        "=" * 72,
        "PAPER NUMBERS — GroundedGuard Detection Comparison",
        "=" * 72,
        "",
    ]

    for model_label, metrics_list in sorted(all_metrics.items()):
        lines += [f"── MODEL: {model_label} " + "─" * 40]
        for m in metrics_list:
            det = m["detector"]
            ci_s  = m["wilson_ci_static"]
            ci_c  = m["wilson_ci_cam"]
            ci_cdg = m["newcombe_ci_cdg"]
            lines += [
                f"  {DETECTOR_DISPLAY.get(det, det)}:",
                f"    IDR_static    = {m['idr_static']:.4f}  "
                f"(95% CI: [{ci_s[0]:.4f}, {ci_s[1]:.4f}])",
                f"    IDR_cam       = {m['idr_cam']:.4f}  "
                f"(95% CI: [{ci_c[0]:.4f}, {ci_c[1]:.4f}])",
                f"    CDG           = {m['cdg']:.4f}  "
                f"(Newcombe CI: [{ci_cdg[0]:.4f}, {ci_cdg[1]:.4f}])",
                f"    Cohen's h gap = {m['cohens_h_gap']:.4f}",
            ]
            # McNemar vs static (camouflage)
            mc = all_mcnemar.get(model_label, {}).get(det)
            if mc and det != "static":
                chi2 = f"{mc['chi2']:.3f}" if mc.get("chi2") else "N/A"
                p    = f"{mc['p']:.4f}"    if mc.get("p")    else "N/A"
                lines.append(
                    f"    McNemar vs static (cam): χ²={chi2}, p={p}  "
                    f"[b={mc['b']}, c={mc['c']}, n={mc['n_pairs']}]"
                )
            lines.append("")

    lines += ["=" * 72, "END", "=" * 72]
    output_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Paper numbers written to: {output_path}")


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    all_trials_by_model = load_all_trials(str(RESULTS_DIR))

    if not all_trials_by_model:
        print(f"No trial files found in {RESULTS_DIR}/")
        print("Run:  python experiments/run_all.py --dry-run")
        sys.exit(1)

    print(f"Computing metrics from: {sorted(all_trials_by_model.keys())}\n")

    all_metrics: dict[str, list[dict]] = {}
    all_mcnemar: dict[str, dict[str, dict]] = {}

    for model_tag, trials in sorted(all_trials_by_model.items()):
        print(f"\n{'='*70}")
        print(f"MODEL: {model_tag}  ({len(trials)} total trials)")
        print(f"{'='*70}")

        static_n = sum(1 for t in trials if t.get("payload_type") == "static")
        cam_n    = sum(1 for t in trials if t.get("payload_type") == "camouflage")
        print(f"  Static: {static_n},  Camouflage: {cam_n}")

        metrics_list = []
        mcnemar_dict: dict[str, dict] = {}

        print(f"\n  {'Detector':<22} {'IDR_s':>8} {'IDR_c':>8} {'CDG':>8} {'h':>7}  CI_cam")
        print(f"  {'─'*72}")

        for dt in DETECTOR_ORDER:
            m = compute_detector_metrics(trials, dt)
            metrics_list.append(m)

            ci_c = m["wilson_ci_cam"]
            marker = " ◄" if dt == "grounded_guard" else ""
            print(
                f"  {DETECTOR_DISPLAY.get(dt, dt):<22} "
                f"{m['idr_static']:>8.4f} "
                f"{m['idr_cam']:>8.4f} "
                f"{m['cdg']:>8.4f} "
                f"{m['cohens_h_gap']:>7.3f}  "
                f"[{ci_c[0]:.3f},{ci_c[1]:.3f}]{marker}"
            )

            if dt != "static":
                mc = compute_mcnemar_vs_static(trials, dt, "camouflage")
                mcnemar_dict[dt] = mc
                p_str = f"p={mc['p']:.4f}" if mc.get("p") else "p=N/A"
                chi2_str = f"χ²={mc['chi2']:.2f}" if mc.get("chi2") else "χ²=N/A"
                stars = ""
                if mc.get("p") and not np.isnan(mc["p"]):
                    if mc["p"] < 0.001: stars = " ***"
                    elif mc["p"] < 0.01: stars = " **"
                    elif mc["p"] < 0.05: stars = " *"
                print(f"    McNemar vs static (cam): {chi2_str}, {p_str}{stars}")

        all_metrics[model_tag] = metrics_list
        all_mcnemar[model_tag] = mcnemar_dict

    # Output files
    RESULTS_DIR.mkdir(exist_ok=True)
    generate_latex_table(all_metrics, RESULTS_DIR / "table_detection_comparison.tex")
    write_paper_numbers(all_metrics, all_mcnemar, RESULTS_DIR / "paper_numbers.txt")

    # Also write machine-readable JSON
    summary_path = RESULTS_DIR / "metrics_summary.json"
    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump({"metrics": all_metrics, "mcnemar": all_mcnemar}, f, indent=2, default=str)
    print(f"Metrics JSON written to: {summary_path}")


if __name__ == "__main__":
    main()
